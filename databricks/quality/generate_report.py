"""
Data Quality Report Generator

Converts the QualityReport from data_quality_checks into a Markdown report
file (DATA_QUALITY_REPORT.md) written to DBFS or the local workspace.

Usage (Databricks notebook):
    %run ./data_quality_checks
    %run ./generate_report

    source_counts = {"borrowers": 5, "loan_products": 5, "loan_accounts": 5, "payments": 10}
    report = run_all_checks(spark, source_counts)
    generate_markdown_report(report, "/dbfs/mnt/reports/DATA_QUALITY_REPORT.md")
"""

from datetime import datetime
from typing import Optional

from data_quality_checks import CheckResult, QualityReport


def generate_markdown_report(
    report: QualityReport,
    output_path: str = "DATA_QUALITY_REPORT.md",
    run_timestamp: Optional[str] = None,
) -> str:
    """
    Generate a Markdown-formatted data quality report.

    Args:
        report: The QualityReport from run_all_checks.
        output_path: File path to write the report.
        run_timestamp: Optional timestamp string; defaults to current time.

    Returns:
        The Markdown content as a string.
    """
    if run_timestamp is None:
        run_timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S UTC")

    overall_status = "PASSED" if report.all_passed else "FAILED"
    status_icon = "Pass" if report.all_passed else "Fail"

    lines = [
        "# Data Quality Report",
        "",
        f"**Run Date:** {run_timestamp}",
        f"**Overall Status:** {overall_status} ({status_icon})",
        f"**Total Checks:** {report.total} | **Passed:** {report.passed} | **Failed:** {report.failed}",
        "",
        "---",
        "",
    ]

    # Group results by category
    categories = {}
    for r in report.results:
        categories.setdefault(r.category, []).append(r)

    for category, checks in categories.items():
        lines.append(f"## {category}")
        lines.append("")
        lines.append("| Status | Table | Check | Detail | Severity |")
        lines.append("|--------|-------|-------|--------|----------|")

        for chk in checks:
            status_str = "PASS" if chk.passed else "FAIL"
            lines.append(
                f"| {status_str} | `{chk.table}` | `{chk.check_name}` | {chk.detail} | {chk.severity} |"
            )

        lines.append("")

    # Summary section
    lines.append("---")
    lines.append("")
    lines.append("## Summary")
    lines.append("")

    if report.all_passed:
        lines.append("All data quality checks passed. The migration is validated.")
    else:
        lines.append(
            "Some data quality checks failed. Review the details above and "
            "address the issues before promoting the data to production."
        )
        lines.append("")
        lines.append("### Failed Checks")
        lines.append("")
        for r in report.results:
            if not r.passed:
                lines.append(f"- **{r.category}** / `{r.table}`.`{r.check_name}`: {r.detail}")

    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append(
        "*Report generated by the Databricks Data Quality Framework "
        "(`databricks/quality/`).*"
    )
    lines.append("")

    content = "\n".join(lines)

    with open(output_path, "w") as f:
        f.write(content)

    print(f"[INFO] Data quality report written to: {output_path}")
    return content


def run_quality_suite_and_report(spark, source_counts: dict, output_path: str = "DATA_QUALITY_REPORT.md"):
    """
    Convenience function: run all checks and generate the report in one call.
    """
    from data_quality_checks import run_all_checks

    report = run_all_checks(spark, source_counts)
    generate_markdown_report(report, output_path)
    return report
