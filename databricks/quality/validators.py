# 4. Business Rule Validation
# ---------------------------------------------------------------------------

def check_business_rules(
    spark: SparkSession,
    report: QualityReport,
) -> None:
    """Validate domain-specific business rules."""

    try:
        loans = spark.table("loan_warehouse.loan_accounts")

        # Rule 1: Active loans must have current_balance > 0
        active_zero_balance = loans.filter(
            (F.col("status") == "ACTIVE") & (F.col("current_balance") <= 0)
        ).count()
        report.add(CheckResult(
            category="Business Rules",
            check_name="active_loan_positive_balance",
            table="loan_accounts",
            passed=active_zero_balance == 0,
            detail=f"{active_zero_balance} active loan(s) with balance <= 0",
            expected="0",
            actual=str(active_zero_balance),
        ))

        # Rule 2: Closed loans should have a maturity_date <= origination_date is invalid
        # (maturity must be after origination for all loans)
        bad_dates = loans.filter(
            F.col("maturity_date") <= F.col("origination_date")
        ).count()
        report.add(CheckResult(
            category="Business Rules",
            check_name="maturity_after_origination",
            table="loan_accounts",
            passed=bad_dates == 0,
            detail=f"{bad_dates} loan(s) where maturity_date <= origination_date",
            expected="0",
            actual=str(bad_dates),
        ))

        # Rule 3: Interest rate should be between 0 and 100
        bad_rates = loans.filter(
            (F.col("interest_rate") < 0) | (F.col("interest_rate") > 100)
        ).count()
        report.add(CheckResult(
            category="Business Rules",
            check_name="interest_rate_range",
            table="loan_accounts",
            passed=bad_rates == 0,
            detail=f"{bad_rates} loan(s) with interest rate outside 0-100%",
            expected="0",
            actual=str(bad_rates),
        ))

        # Rule 4: LTV percent should be between 0 and 200 (if present)
        bad_ltv = loans.filter(
            F.col("ltv_percent").isNotNull() &
            ((F.col("ltv_percent") < 0) | (F.col("ltv_percent") > 200))
        ).count()
        report.add(CheckResult(
            category="Business Rules",
            check_name="ltv_percent_range",
            table="loan_accounts",
            passed=bad_ltv == 0,
            detail=f"{bad_ltv} loan(s) with LTV outside 0-200%",
            expected="0",
            actual=str(bad_ltv),
        ))

        # Rule 5: Delinquency days >= 0
        bad_dlq = loans.filter(F.col("delinquency_days") < 0).count()
        report.add(CheckResult(
            category="Business Rules",
            check_name="delinquency_non_negative",
            table="loan_accounts",
            passed=bad_dlq == 0,
            detail=f"{bad_dlq} loan(s) with negative delinquency days",
            expected="0",
            actual=str(bad_dlq),
        ))

    except Exception as e:
        report.add(CheckResult(
            category="Business Rules",
            check_name="loan_business_rules",
            table="loan_accounts",
            passed=False,
            detail=f"Error: {e}",
        ))

    # Payment business rules
    try:
        payments = spark.table("loan_warehouse.payments")

        # Rule 6: Payment total_amount > 0 for POSTED payments
        bad_amounts = payments.filter(
            (F.col("status") == "POSTED") & (F.col("total_amount") <= 0)
        ).count()
        report.add(CheckResult(
            category="Business Rules",
            check_name="posted_payment_positive_amount",
            table="payments",
            passed=bad_amounts == 0,
            detail=f"{bad_amounts} posted payment(s) with amount <= 0",
            expected="0",
            actual=str(bad_amounts),
        ))

        # Rule 7: Payment component sum should approximate total
        # (principal + interest + escrow + late_fee ≈ total_amount)
        component_check = payments.filter(
            F.col("status") == "POSTED"
        ).withColumn(
            "_component_sum",
            F.coalesce(F.col("principal_amount"), F.lit(0)) +
            F.coalesce(F.col("interest_amount"), F.lit(0)) +
            F.coalesce(F.col("escrow_amount"), F.lit(0)) +
            F.coalesce(F.col("late_fee"), F.lit(0))
        ).withColumn(
            "_diff", F.abs(F.col("total_amount") - F.col("_component_sum"))
        )
        mismatched = component_check.filter(F.col("_diff") > 0.02).count()
        report.add(CheckResult(
            category="Business Rules",
            check_name="payment_component_sum",
            table="payments",
            passed=mismatched == 0,
            detail=f"{mismatched} payment(s) where components don't sum to total (tolerance $0.02)",
            expected="0",
            actual=str(mismatched),
        ))

    except Exception as e:
        report.add(CheckResult(
            category="Business Rules",
            check_name="payment_business_rules",
            table="payments",
            passed=False,
            detail=f"Error: {e}",
        ))

    # Borrower business rules
    try:
        borrowers = spark.table("loan_warehouse.borrowers")

        # Rule 8: Credit score should be between 300 and 850 (if present)
        bad_credit = borrowers.filter(
            F.col("credit_score").isNotNull() &
            ((F.col("credit_score") < 300) | (F.col("credit_score") > 850))
        ).count()
        report.add(CheckResult(
            category="Business Rules",
            check_name="credit_score_range",
            table="borrowers",
            passed=bad_credit == 0,
            detail=f"{bad_credit} borrower(s) with credit score outside 300-850",
            expected="0",
            actual=str(bad_credit),
        ))

        # Rule 9: Annual income should be non-negative (if present)
        bad_income = borrowers.filter(
            F.col("annual_income").isNotNull() & (F.col("annual_income") < 0)
        ).count()
        report.add(CheckResult(
            category="Business Rules",
            check_name="annual_income_non_negative",
            table="borrowers",
            passed=bad_income == 0,
            detail=f"{bad_income} borrower(s) with negative annual income",
            expected="0",
            actual=str(bad_income),
        ))

    except Exception as e:
        report.add(CheckResult(
            category="Business Rules",
            check_name="borrower_business_rules",
            table="borrowers",
            passed=False,
            detail=f"Error: {e}",
        ))


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def run_all_checks(
    spark: SparkSession,
    source_counts: dict,
    report_path: str = "dbfs:/mnt/reports/data_quality/",
) -> QualityReport:
    """
    Execute all data quality checks and generate the report.

    Parameters:
        spark          : Active SparkSession
        source_counts  : Dict of expected row counts per table
        report_path    : DBFS path to write the markdown report

    Returns:
        QualityReport with all check results
    """
    report = QualityReport()

    print("=" * 70)
    print("Data Quality Validation")
    print(f"Started: {report.generated_at}")
    print("=" * 70)

    print("\n--- Row Count Reconciliation ---")
    check_row_counts(spark, report, source_counts)

    print("\n--- Null Checks ---")
    check_nulls(spark, report)

    print("\n--- Referential Integrity ---")
    check_referential_integrity(spark, report)

    print("\n--- Business Rules ---")
    check_business_rules(spark, report)

    # Generate markdown report
    print(f"\n--- Writing report to {report_path} ---")
    markdown_content = report.write_markdown(report_path, spark)

    print(f"\nOverall: {'PASS' if report.all_passed else 'FAIL'} "
          f"({report.passed_count}/{report.total_count} checks passed)")

    return report
